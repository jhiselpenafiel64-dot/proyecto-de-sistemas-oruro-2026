<?php
declare(strict_types=1);

define('DATABASE_URL', getenv('DATABASE_URL') ?: '');
define('DB_HOST', getenv('DB_HOST') ?: '127.0.0.1');
define('DB_NAME', getenv('DB_NAME') ?: 'la_polar');
define('DB_USER', getenv('DB_USER') ?: 'postgres');
define('DB_PASSWORD', getenv('DB_PASSWORD') ?: '');
define('DB_PORT', getenv('DB_PORT') ?: '5432');
define('GOOGLE_CLIENT_ID', getenv('GOOGLE_CLIENT_ID') ?: '');

function db(): PDO
{
    static $connection;
    if ($connection instanceof PDO) {
        return $connection;
    }

    if (DATABASE_URL !== '') {
        $parts = parse_url(DATABASE_URL);
        if (!is_array($parts) || empty($parts['host']) || empty($parts['path'])) {
            throw new RuntimeException('DATABASE_URL no tiene un formato PostgreSQL válido.');
        }
        $host = $parts['host'];
        $port = (string) ($parts['port'] ?? 5432);
        $database = ltrim($parts['path'], '/');
        $user = rawurldecode((string) ($parts['user'] ?? ''));
        $password = rawurldecode((string) ($parts['pass'] ?? ''));
        if ($database === '' || $user === '') {
            throw new RuntimeException('DATABASE_URL no contiene el nombre de la base o el usuario.');
        }
        $dsn = 'pgsql:host=' . $host . ';port=' . $port . ';dbname=' . $database . ';sslmode=require';
        $connection = new PDO($dsn, $user, $password);
    } else {
        $dsn = 'pgsql:host=' . DB_HOST . ';port=' . DB_PORT . ';dbname=' . DB_NAME;
        $connection = new PDO($dsn, DB_USER, DB_PASSWORD);
    }

    $connection->setAttribute(PDO::ATTR_ERRMODE, PDO::ERRMODE_EXCEPTION);
    $connection->setAttribute(PDO::ATTR_DEFAULT_FETCH_MODE, PDO::FETCH_ASSOC);
    $connection->setAttribute(PDO::ATTR_EMULATE_PREPARES, false);
    return $connection;
}

function withSchemaLock(PDO $connection, string $name, callable $callback): void
{
    $lock = $connection->prepare('SELECT pg_advisory_lock(hashtext(?))');
    $lock->execute([$name]);
    try {
        $callback();
    } finally {
        $unlock = $connection->prepare('SELECT pg_advisory_unlock(hashtext(?))');
        $unlock->execute([$name]);
    }
}

function ensureInventarioSchema(PDO $connection): void
{
    withSchemaLock($connection, 'la_polar_inventario_schema', static function () use ($connection): void {
        $connection->exec("CREATE TABLE IF NOT EXISTS inventario_lotes (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            producto_id INTEGER NOT NULL REFERENCES productos(id),
            cantidad_inicial INTEGER NOT NULL CHECK (cantidad_inicial >= 0),
            cantidad_disponible INTEGER NOT NULL CHECK (cantidad_disponible >= 0),
            fecha_ingreso DATE NOT NULL,
            fecha_vencimiento DATE NULL,
            origen VARCHAR(20) NOT NULL DEFAULT 'Entrada' CHECK (origen IN ('Inicial', 'Entrada')),
            usuario_id INTEGER NULL REFERENCES usuarios(id) ON DELETE SET NULL,
            creado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
        )");
        $connection->exec('CREATE INDEX IF NOT EXISTS idx_inventario_lote_stock ON inventario_lotes (producto_id, cantidad_disponible, fecha_vencimiento)');
        $connection->exec("CREATE TABLE IF NOT EXISTS inventario_movimientos (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            producto_id INTEGER NOT NULL REFERENCES productos(id),
            lote_id BIGINT NULL REFERENCES inventario_lotes(id) ON DELETE SET NULL,
            pedido_id BIGINT NULL REFERENCES pedidos(id) ON DELETE SET NULL,
            usuario_id INTEGER NULL REFERENCES usuarios(id) ON DELETE SET NULL,
            tipo VARCHAR(20) NOT NULL CHECK (tipo IN ('Entrada', 'Salida', 'Baja', 'Reintegro', 'Inicial')),
            cantidad INTEGER NOT NULL CHECK (cantidad >= 0),
            fecha_movimiento DATE NOT NULL,
            motivo VARCHAR(50) NULL,
            observacion VARCHAR(255) NULL,
            creado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
        )");
        $connection->exec('CREATE INDEX IF NOT EXISTS idx_inventario_movimiento_fecha ON inventario_movimientos (fecha_movimiento, tipo)');
        $connection->exec('CREATE INDEX IF NOT EXISTS idx_inventario_movimiento_producto ON inventario_movimientos (producto_id, fecha_movimiento)');
        $connection->exec('CREATE INDEX IF NOT EXISTS idx_inventario_movimiento_pedido ON inventario_movimientos (pedido_id, tipo)');
        $connection->exec("INSERT INTO inventario_lotes
            (producto_id, cantidad_inicial, cantidad_disponible, fecha_ingreso, fecha_vencimiento, origen)
            SELECT p.id, p.stock, p.stock, CURRENT_DATE, NULL, 'Inicial'
            FROM productos p
            WHERE NOT EXISTS (SELECT 1 FROM inventario_lotes l WHERE l.producto_id = p.id)");
        $connection->exec("INSERT INTO inventario_movimientos
            (producto_id, lote_id, tipo, cantidad, fecha_movimiento, motivo, observacion)
            SELECT l.producto_id, l.id, 'Inicial', l.cantidad_inicial, l.fecha_ingreso,
                'Migración de stock existente', 'Stock disponible antes del control por lotes'
            FROM inventario_lotes l
            WHERE l.origen = 'Inicial' AND l.cantidad_inicial > 0
                AND NOT EXISTS (
                    SELECT 1 FROM inventario_movimientos m
                    WHERE m.lote_id = l.id AND m.tipo = 'Inicial'
                )");
    });
}

function ensureArqueoSchema(PDO $connection): void
{
    withSchemaLock($connection, 'la_polar_arqueo_schema', static function () use ($connection): void {
        $columnExists = static function (string $table, string $column) use ($connection): bool {
            $stmt = $connection->prepare('SELECT EXISTS (
                SELECT 1 FROM information_schema.columns
                WHERE table_schema = current_schema() AND table_name = ? AND column_name = ?
            )');
            $stmt->execute([$table, $column]);
            return $stmt->fetchColumn() === true || $stmt->fetchColumn() === 't';
        };
        $tableExists = static function (string $table) use ($connection): bool {
            $stmt = $connection->prepare('SELECT to_regclass(?) IS NOT NULL');
            $stmt->execute([$table]);
            $value = $stmt->fetchColumn();
            return $value === true || $value === 't';
        };

        if ($tableExists('pagos') && !$columnExists('pagos', 'pagado_en')) {
            $connection->exec('ALTER TABLE pagos ADD COLUMN pagado_en TIMESTAMP NULL');
            $connection->exec("UPDATE pagos SET pagado_en = creado_en WHERE estado = 'Pagado' AND pagado_en IS NULL");
        }
        if ($tableExists('pagos')) {
            $connection->exec('CREATE INDEX IF NOT EXISTS idx_pagos_metodo_estado_pagado ON pagos (metodo, estado, pagado_en)');
        }
        if (!$tableExists('arqueos_caja')) {
            $connection->exec("CREATE TABLE arqueos_caja (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                usuario_apertura_id INTEGER NOT NULL REFERENCES usuarios(id),
                usuario_cierre_id INTEGER NULL REFERENCES usuarios(id) ON DELETE SET NULL,
                efectivo_inicial NUMERIC(10,2) NOT NULL DEFAULT 0,
                efectivo_ventas NUMERIC(10,2) NOT NULL DEFAULT 0,
                efectivo_egresos NUMERIC(10,2) NOT NULL DEFAULT 0,
                efectivo_contado NUMERIC(10,2) NULL,
                diferencia NUMERIC(10,2) NULL,
                apertura TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
                cierre TIMESTAMP NULL,
                caja_activa SMALLINT GENERATED ALWAYS AS (CASE WHEN cierre IS NULL THEN 1 ELSE NULL END) STORED
            )");
            $connection->exec('CREATE UNIQUE INDEX IF NOT EXISTS uq_arqueo_caja_activa ON arqueos_caja (caja_activa)');
            $connection->exec('CREATE INDEX IF NOT EXISTS idx_arqueos_caja_apertura ON arqueos_caja (apertura)');
        } elseif (!$columnExists('arqueos_caja', 'efectivo_egresos')) {
            $connection->exec('ALTER TABLE arqueos_caja ADD COLUMN efectivo_egresos NUMERIC(10,2) NOT NULL DEFAULT 0');
        }
        if (!$tableExists('arqueo_egresos')) {
            $connection->exec("CREATE TABLE arqueo_egresos (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                arqueo_caja_id BIGINT NOT NULL REFERENCES arqueos_caja(id),
                usuario_id INTEGER NULL REFERENCES usuarios(id) ON DELETE SET NULL,
                categoria VARCHAR(60) NOT NULL,
                concepto VARCHAR(160) NOT NULL,
                monto NUMERIC(10,2) NOT NULL,
                creado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
            )");
            $connection->exec('CREATE INDEX IF NOT EXISTS idx_arqueo_egresos_caja_creado ON arqueo_egresos (arqueo_caja_id, creado_en)');
        }
    });
}

function jsonResponse(array $data, int $status = 200): never
{
    http_response_code($status);
    header('Content-Type: application/json; charset=utf-8');
    echo json_encode($data, JSON_UNESCAPED_UNICODE);
    exit;
}

function requestBody(): array
{
    $body = json_decode(file_get_contents('php://input'), true);
    return is_array($body) ? $body : $_POST;
}

function requireLogin(): array
{
    if (empty($_SESSION['usuario'])) {
        jsonResponse(['ok' => false, 'mensaje' => 'Sesión no autorizada.'], 401);
    }
    return $_SESSION['usuario'];
}
